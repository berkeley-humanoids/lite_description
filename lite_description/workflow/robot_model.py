"""The URDF parsing, joint lookups and file helpers that the generator stages share."""

from collections.abc import Callable
from pathlib import Path
import re
import xml.etree.ElementTree as ET

from lite_description import ROBOTS_DIR


def resolve_robot_dir(robot: str) -> Path:
    """Return ``robots/<robot>/`` of the checkout.

    The installed package leaves the ``cad/`` inputs out, so the generator runs from a
    checkout only.
    """
    cad_dir = ROBOTS_DIR / robot / "cad"
    if not cad_dir.is_dir():
        raise FileNotFoundError(f"{cad_dir} does not exist. Run the generator from a checkout.")
    return cad_dir.parent


def parse(urdf_path: Path) -> ET.ElementTree:
    """Parse a URDF, and keep its comments."""
    return ET.parse(urdf_path, parser=ET.XMLParser(target=ET.TreeBuilder(insert_comments=True)))


def root_link(root: ET.Element) -> str:
    """Return the name of the one link that is not the child of a joint."""
    children = {joint.find("child").get("link") for joint in root.findall("joint")}
    roots = [link.get("name") for link in root.findall("link") if link.get("name") not in children]
    if len(roots) != 1:
        raise ValueError(f"Expected one root link, found {roots}.")
    return roots[0]


def joint_limits(root: ET.Element) -> dict[str, dict[str, float]]:
    """Return {joint: {"lower", "upper"}} of each joint with a ``<limit>``, in radians."""
    return {
        joint.get("name"): {"lower": float(limit.get("lower")), "upper": float(limit.get("upper"))}
        for joint in root.findall("joint")
        if (limit := joint.find("limit")) is not None
    }


_REQUIRED = object()


def joint_property(joint: str, joint_properties: dict, key: str, default=_REQUIRED):
    """Return ``key`` of ``joint`` in joint_properties.json.

    An exact joint name wins over a regex key. A key that starts with ``_`` is a note.
    Without ``default``, a missing key raises ``ValueError``.
    """
    config = joint_properties.get(joint)
    if config is None:
        config = next(
            (value for pattern, value in joint_properties.items()
             if not pattern.startswith("_") and re.fullmatch(pattern, joint)),
            {},
        )
    if key not in config:
        if default is not _REQUIRED:
            return default
        raise ValueError(f"joint_properties.json gives no {key!r} for joint {joint!r}.")
    return config[key]


def rewrite_mesh_filenames(root: ET.Element, rewrite: Callable[[str], str]) -> None:
    """Rewrite each ``<mesh filename>``. ``rewrite`` gets the file name without its directory."""
    for mesh in root.iter("mesh"):
        mesh.set("filename", rewrite(Path(mesh.get("filename")).name))


def autogen_comment(robot: str) -> str:
    """Return the text of the banner comment at the top of each generated file."""
    # An XML comment cannot contain "--".
    return (
        f" GENERATED by lite_description.workflow from Onshape CAD. Do not edit by hand. "
        f"Regenerate: lite-description-generate {robot} "
    )
